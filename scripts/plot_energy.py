os.environ.setdefault("MPLCONFIGDIR", os.path.join("/tmp", "matplotlib"))
os.makedirs(os.environ["MPLCONFIGDIR"], exist_ok=True)

import matplotlib

matplotlib.use("Agg")
import pandas as pd

from vessim.visualization import (
    plot_budget_distribution,
    plot_budget_vs_forecast,
    plot_carbon_analysis,
    plot_cluster_dashboard,
    plot_cluster_job_timeline,
    plot_frequency_timeline,
    plot_combined_gantt_chart,
    plot_combined_puzzle,
    plot_job_analysis,
    plot_job_arrivals,
    plot_job_event_timeline,
    plot_job_metrics,
    plot_queue_evolution,
    plot_result_df,
)


SCHEDULERS_FILE = "schedulers.pkl"
RESULTS_CSV = "energy_simulation_result.csv"
CRITICAL_TASKS = {"carbon_analysis"}
MEMORY_HEAVY_TASKS = {"job_event_timeline"}
LARGE_SCHEDULER_PICKLE_BYTES = 128 * 1024 * 1024

TASK_OUTPUTS = {
    "energy_results": ("energy_results.png",),
    "cluster_dashboard": ("cluster_dashboard.png",),
    "job_analysis": ("job_analysis.png",),
    "job_arrivals": ("job_arrivals.png",),
    "job_event_timeline": ("job_event_timeline.html",),
    "queue_evolution": ("queue_evolution.png",),
    "budget_distribution": ("budget_distribution.png",),
    "frequency_timeline": ("frequency_timeline.png",),
    "carbon_analysis": ("carbon_analysis.png", "carbon_metrics.csv"),
    "job_metrics": ("job_metrics.png",),
    "cluster_job_timeline": ("cluster_job_timeline.png",),
    "gantt_combined": ("gantt_combined.png",),
    # puzzle_combined stays callable (see plot_combined_puzzle and the
    # --puzzle-plan / --real-puzzle CLI paths) but is no longer generated by
    # default; the default puzzle view is the single budget-vs-forecast chart.
    "puzzle_combined": ("puzzle_combined.png",),
    "budget_vs_forecast": ("budget_vs_forecast.png",),
}
PUZZLE_FORECAST_FILES = ("puzzle_forecast_slots.csv", "puzzle_forecast_jobs.csv")


def load_schedulers(results_dir: str):
    schedulers_path = os.path.join(results_dir, SCHEDULERS_FILE)
    with open(schedulers_path, "rb") as f:
        return pickle.load(f)


def load_results_df(results_dir: str):
    return pd.read_csv(
        os.path.join(results_dir, RESULTS_CSV),
        index_col=0,
        parse_dates=True,
    )


def _task_needs_df(task_name: str) -> bool:
    return task_name in {
        "energy_results",
        "cluster_dashboard",
        "job_event_timeline",
        "budget_distribution",
        "carbon_analysis",
        "budget_vs_forecast",
    }


def _task_needs_schedulers(task_name: str) -> bool:
    return (
        task_name
        in {
            "cluster_dashboard",
            "job_analysis",
            "job_arrivals",
            "job_event_timeline",
            "queue_evolution",
            "budget_distribution",
            "frequency_timeline",
            "carbon_analysis",
            "job_metrics",
            "cluster_job_timeline",
            "gantt_combined",
        }
    )


def _has_puzzle_forecasts(results_dir: str) -> bool:
    return all(
        os.path.exists(os.path.join(results_dir, f))
        for f in PUZZLE_FORECAST_FILES
    )


def _run_plot_task(task_name, results_dir, df=None, schedulers=None):
    import os
    try:
        if df is None and _task_needs_df(task_name):
            df = load_results_df(results_dir)
        if schedulers is None and _task_needs_schedulers(task_name):
            schedulers = load_schedulers(results_dir)

        if task_name == "energy_results":
            plot_result_df(df, output_file=os.path.join(results_dir, "energy_results.png"), min_soc=0.2)
        elif task_name == "cluster_dashboard":
            plot_cluster_dashboard(df, schedulers, output_file=os.path.join(results_dir, "cluster_dashboard.png"), min_soc=0.2)
        elif task_name == "job_analysis":
            plot_job_analysis(schedulers, output_file=os.path.join(results_dir, "job_analysis.png"))
        elif task_name == "job_arrivals":
            plot_job_arrivals(schedulers, output_file=os.path.join(results_dir, "job_arrivals.png"))
        elif task_name == "job_event_timeline":
            plot_job_event_timeline(
                df,
                schedulers,
                output_file=os.path.join(results_dir, "job_event_timeline.html"),
            )
        elif task_name == "queue_evolution":
            plot_queue_evolution(
                results_dir,
                schedulers=schedulers,
                output_file=os.path.join(results_dir, "queue_evolution.png"),
            )
        elif task_name == "budget_distribution":
            plot_budget_distribution(df, schedulers, output_file=os.path.join(results_dir, "budget_distribution.png"))
        elif task_name == "frequency_timeline":
            plot_frequency_timeline(schedulers, output_file=os.path.join(results_dir, "frequency_timeline.png"))
        elif task_name == "carbon_analysis":
            plot_carbon_analysis(df, schedulers, plot_output=os.path.join(results_dir, "carbon_analysis.png"), csv_output=os.path.join(results_dir, "carbon_metrics.csv"))
        elif task_name == "job_metrics":
            plot_job_metrics(schedulers, output_file=os.path.join(results_dir, "job_metrics.png"))
        elif task_name == "cluster_job_timeline":
            plot_cluster_job_timeline(schedulers, output_file=os.path.join(results_dir, "cluster_job_timeline.png"))
        elif task_name == "gantt_combined":
            plot_combined_gantt_chart(schedulers, output_file=os.path.join(results_dir, "gantt_combined.png"), max_nodes=20)
        elif task_name == "puzzle_combined":
            plot_combined_puzzle(results_dir)
        elif task_name == "budget_vs_forecast":
            plot_budget_vs_forecast(
                results_dir,
                df=df,
                output_file=os.path.join(results_dir, "budget_vs_forecast.png"),
            )
        return task_name, True, None
    except Exception as e:
        import traceback
        return task_name, False, str(e) + "\n" + traceback.format_exc()


def _run_plot_task_from_disk(task_name, results_dir):
    return _run_plot_task(task_name, results_dir)


def _plot_worker_count(task_count: int, requested_workers: int | None = None) -> int:
    if requested_workers is None:
        raw_workers = os.environ.get("WAVE_PLOT_WORKERS")
        if raw_workers is None:
            requested_workers = min(12, os.cpu_count() or 2)
        else:
            try:
                requested_workers = int(raw_workers)
            except ValueError:
                requested_workers = min(12, os.cpu_count() or 2)

    return max(1, min(task_count, requested_workers))


def safe_print(msg: str):
    import sys
    try:
        print(msg)
    except UnicodeEncodeError:
        encoding = sys.stdout.encoding or 'ascii'
        encoded_msg = msg.encode(encoding, errors='replace').decode(encoding)
        print(encoded_msg)


def _run_plot_tasks_sequential(task_names, results_dir, df, schedulers) -> None:
    for name in task_names:
        task_name, success, err = _run_plot_task(name, results_dir, df, schedulers)
        if not success:
            safe_print(f"Plot '{task_name}' failed: {err}")


def _run_plot_tasks_parallel(task_names, results_dir, workers: int) -> set[str]:
    failed_tasks = set()
    with ProcessPoolExecutor(max_workers=workers) as executor:
        futures = {
            executor.submit(_run_plot_task_from_disk, name, results_dir): name
            for name in task_names
        }
        for future in as_completed(futures):
            name = futures[future]
            try:
                task_name, success, err = future.result()
                if not success:
                    failed_tasks.add(task_name)
                    safe_print(f"Plot '{task_name}' failed: {err}")
            except Exception as e:
                failed_tasks.add(name)
                safe_print(f"Plot task '{name}' crashed: {e}")
    return failed_tasks


def _expected_outputs(task_name: str, results_dir: str) -> list[str]:
    if task_name.startswith("gantt_"):
        return [os.path.join(results_dir, f"{task_name}.png")]
    return [os.path.join(results_dir, name) for name in TASK_OUTPUTS.get(task_name, ())]


def _missing_outputs(task_names, results_dir) -> list[str]:
    missing = []
    for task_name in task_names:
        outputs = _expected_outputs(task_name, results_dir)
        if outputs and any(not os.path.exists(path) for path in outputs):
            missing.append(task_name)
    return missing


def _run_plot_group(group_name: str, task_names, results_dir: str, workers: int) -> None:
    if not task_names:
        return
    _run_plot_tasks_parallel(task_names, results_dir, workers)


def generate_plots(
    results_dir: str,
    schedulers=None,
    plot_workers: int | None = None,
) -> None:
    t0 = _time.time()
    if schedulers is None:
        schedulers = load_schedulers(results_dir)

    task_names = [
        "energy_results",
        "cluster_dashboard",
        "job_analysis",
        "job_arrivals",
        "job_event_timeline",
        "queue_evolution",
        "budget_distribution",
        "frequency_timeline",
        "carbon_analysis",
        "job_metrics",
        "cluster_job_timeline",
    ]
    task_names.append("gantt_combined")
    if _has_puzzle_forecasts(results_dir):
        task_names.append("budget_vs_forecast")

    workers = _plot_worker_count(len(task_names), plot_workers)
    schedulers_path = os.path.join(results_dir, SCHEDULERS_FILE)
    worker_override = (
        plot_workers is not None
        or os.environ.get("WAVE_PLOT_WORKERS") is not None
    )
    if (
        not worker_override
        and os.path.exists(schedulers_path)
        and os.path.getsize(schedulers_path) >= LARGE_SCHEDULER_PICKLE_BYTES
    ):
        workers = 1

    if workers == 1:
        df = load_results_df(results_dir)
        print(f"[{_time.time() - t0:.2f}s] Generating {len(task_names)} plots sequentially...")
        _run_plot_tasks_sequential(task_names, results_dir, df, schedulers)
    else:
        print(
            f"[{_time.time() - t0:.2f}s] Generating {len(task_names)} plots "
            f"with ProcessPoolExecutor batches (max_workers={workers})..."
        )

        critical_tasks = [name for name in task_names if name in CRITICAL_TASKS]
        heavy_tasks = [name for name in task_names if name in MEMORY_HEAVY_TASKS]
        parallel_tasks = [
            name
            for name in task_names
            if name not in CRITICAL_TASKS and name not in MEMORY_HEAVY_TASKS
        ]

        # Carbon metrics feed the GUI summary, so generate them first in an
        # isolated process. The large HTML timeline is isolated at the end so a
        # memory spike cannot break the pool while PNG/CSV tasks are pending.
        _run_plot_group("critical", critical_tasks, results_dir, workers=1)
        _run_plot_group("parallel", parallel_tasks, results_dir, workers=workers)
        _run_plot_group("heavy", heavy_tasks, results_dir, workers=1)

        missing = _missing_outputs(task_names, results_dir)
        if missing:
            safe_print(
                f"Retrying {len(missing)} plot task(s) with missing output files: "
                f"{', '.join(missing)}"
            )
            _run_plot_tasks_parallel(missing, results_dir, workers=1)

            still_missing = _missing_outputs(task_names, results_dir)
            if still_missing:
                safe_print(
                    "Missing plot outputs after retry: "
                    + ", ".join(still_missing)
                )

    print(f"\n[{_time.time() - t0:.2f}s] All plots saved!")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate plots for a simulation result directory.")
    parser.add_argument("results_dir", help="Path to a results_* directory.")
    parser.add_argument(
        "--workers",
        type=int,
        default=None,
        help="Number of parallel plot workers. Default is min(12, CPU count).",
    )
    parser.add_argument(
        "--puzzle-plan",
        default=None,
        help=(
            "Render ONLY the puzzle plan-vs-execution plot for the given "
            "selector, skipping all other plots. Accepts a plan id, a "
            "comma-separated list, or 'first' / 'latest' / 'all' / 'worst' "
            "(the plan with the most grid spills). Loads the result data once "
            "and reuses it across every plan rendered."
        ),
    )
    parser.add_argument(
        "--real-puzzle",
        action="store_true",
        help=(
            "Render ONLY the real-execution 'gantt-puzzle' view (real_puzzle.png) "
            "with the renewable envelope as a green board. Works for ANY budget "
            "policy (no puzzle forecast needed), so different policies can be "
            "compared on the same canvas."
        ),
    )
    args = parser.parse_args()

    # Fast iteration path: only (re)build the puzzle plot for the chosen plan(s).
    if args.puzzle_plan is not None:
        if not _has_puzzle_forecasts(args.results_dir):
            raise SystemExit(
                "No puzzle forecast CSVs in this results dir. Run a simulation "
                "with --budget-policy puzzle first."
            )
        plot_combined_puzzle(args.results_dir, plan_id=args.puzzle_plan)
        return

    # Policy-agnostic execution puzzle: works with any budget policy.
    if args.real_puzzle:
        plot_combined_puzzle(args.results_dir, real_only=True)
        return

    generate_plots(args.results_dir, plot_workers=args.workers)


if __name__ == "__main__":
    main()
